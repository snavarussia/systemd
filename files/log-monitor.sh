#!/usr/bin/env bash

# Не завершать скрипт автоматически при ошибках, но завершить его при использовании несуществующей переменной.
set -u

# Файл конфигурации, из которого будут получены переменные LOG_FILE и KEYWORD.
CONFIG="/etc/sysconfig/log-monitor"

# Проверяем, существует ли файл конфигурации. Если файла нет — выводим сообщение об ошибке и завершаем скрипт с кодом 1.
[[ -f "$CONFIG" ]] || { echo "Missing $CONFIG"; exit 1; }

# Загружаем переменные и настройки из файла конфигурации. После выполнения этой команды переменные LOG_FILE и KEYWORD становятся доступными в текущем скрипте.
source "$CONFIG"

# Проверяем, что переменная LOG_FILE существует и содержит какое-либо значение.
# Если переменная не задана или пустая: выводится сообщение "LOG_FILE is not configured", после чего скрипт завершается с ошибкой.
: "${LOG_FILE:?LOG_FILE is not configured}"

# Проверяем, что переменная KEYWORD существует и содержит какое-либо значение.
# Если переменная не задана или пустая: выводится сообщение "KEYWORD is not configured", после чего скрипт завершается с ошибкой.
: "${KEYWORD:?KEYWORD is not configured}"

# Проверяем, существует ли файл журнала, который указан в переменной LOG_FILE. Если файла нет — выводим сообщение об ошибке.
[[ -f "$LOG_FILE" ]] || { echo "Log file $LOG_FILE does not exist"; exit 1; }

# Ищем заданное ключевое слово в файле журнала.
# grep:
# -F — искать обычную строку, а не регулярное выражение;
# -q — не выводить найденную строку, нужен только код возврата;
# -- — обозначает конец параметров grep.
# "$KEYWORD"  — что ищем;
# "$LOG_FILE" — в каком файле ищем.
if grep -Fq -- "$KEYWORD" "$LOG_FILE"; then
  echo "Keyword '$KEYWORD' found in $LOG_FILE"
else
  echo "Keyword '$KEYWORD' not found in $LOG_FILE"
fi
